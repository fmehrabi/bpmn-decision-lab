#!/usr/bin/env python3
"""Build the browser-friendly data bundle from the canonical JSON files."""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = {
    "processCase": ROOT / "data" / "process-case.json",
    "improvementActions": ROOT / "data" / "improvement-actions.json",
    "assessment": ROOT / "data" / "assessment.json",
}

def main() -> None:
    payload = {key: json.loads(path.read_text(encoding="utf-8")) for key, path in FILES.items()}
    if payload["assessment"]["questionCount"] != len(payload["assessment"]["questions"]):
        raise SystemExit("Assessment questionCount does not match questions array")
    out = "/* Generated by scripts/build-data.py. Edit data/*.json, then rebuild. */\n"
    out += "window.BPMN_LAB_DATA = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n"
    target = ROOT / "assets" / "data.js"
    target.write_text(out, encoding="utf-8")
    print(f"Wrote {target.relative_to(ROOT)} ({target.stat().st_size:,} bytes)")

if __name__ == "__main__":
    main()
